interface PlayerCaching {
    fun loadCurrentPlayers(): List<Player>
    fun loadHistoricalPlayers(): List<Player>
    /** Rows from `liveSeason` on are the expiring server tier; everything before it is permanent history. */
    fun saveCurrentPlayers(players: List<Player>, liveSeason: Int)
    /** One bundled season, or the career rollup for [StatScoutSeason.ALL_TIME]. */
    fun loadHistoricalSeason(season: Int): List<Player> = emptyList()
    /** The newest bundled season no later than `season`: what an offline cold start can show. */
    fun loadNewestBundledSeason(atMost: Int): List<Player> = emptyList()
}

/**
 * The bundled archive plus the last server snapshot of the live season.
 *
 * History ships in the APK as one gzip JSON asset per season
 * (`players-historical-<season>.bin`, generated by
 * `scripts/sync-android-historical.py`) and is never fetched. The archive carries
 * the live season too while the next has not published, so the tiers overlap on
 * purpose: the server copy wins when present. The live season is saved only after
 * a server response passes [PlayerSnapshotValidator], with a provenance marker
 * beside it, so nothing but server data is ever restored.
 */
class TwoTierPlayerCache(
    private val directory: File,
    private val openHistorical: (String) -> InputStream?,
) : PlayerCaching {
    private val currentFile = File(directory, "players-current.json")
    private val provenanceFile = File(directory, "players-current-provenance.json")

    override fun loadCurrentPlayers(): List<Player> {
        if (!hasServerProvenance()) {
            currentFile.delete()
            provenanceFile.delete()
            return emptyList()
        }
        val cached = runCatching { currentFile.inputStream().use { readPlayers(it) } }.getOrNull() ?: return emptyList()
        return if (PlayerSnapshotValidator.isCompleteCurrent(cached)) cached else emptyList()
    }

    /** Every bundled season, decoded in parallel. Callers merge it under server rows, never over them. */
    override fun loadHistoricalPlayers(): List<Player> {
        val seasons = bundledSeasons
        val results = arrayOfNulls<List<Player>>(seasons.size)
        val threads = seasons.mapIndexed { index, season ->
            Thread { results[index] = loadHistoricalSeason(season) }.also { it.start() }
        }
        threads.forEach { it.join() }
        return results.flatMap { it.orEmpty() }
    }

    override fun loadHistoricalSeason(season: Int): List<Player> {
        val stream = openHistorical("$HISTORY_PREFIX$season.bin") ?: return emptyList()
        return runCatching { GZIPInputStream(stream.buffered(1 shl 16), 1 shl 16).use { readPlayers(it) } }.getOrDefault(emptyList())
    }

    override fun loadNewestBundledSeason(atMost: Int): List<Player> {
        val newest = bundledSeasons.filter { it != StatScoutSeason.ALL_TIME && it <= atMost }.maxOrNull() ?: return emptyList()
        return loadHistoricalSeason(newest)
    }

    override fun saveCurrentPlayers(players: List<Player>, liveSeason: Int) {
        val current = players.filter { (it.season ?: 0) >= liveSeason }
        if (current.isEmpty() || !PlayerSnapshotValidator.isCompleteCurrent(current)) return
        directory.mkdirs()
        val tmp = File(directory, "players-current.json.tmp")
        tmp.outputStream().bufferedWriter().use { writer ->
            writer.write(buildJsonArray { current.forEach { add(it.toJson()) } }.toString())
        }
        if (!tmp.renameTo(currentFile)) {
            tmp.delete()
            return
        }
        // Only after the rows are down, so a failed write never leaves a marker vouching for nothing.
        provenanceFile.writeText(buildJsonObject {
            put("schema", PROVENANCE_SCHEMA)
            put("savedAt", Instant.now().toString())
        }.toString())
    }

    private fun hasServerProvenance(): Boolean {
        val text = runCatching { provenanceFile.readText() }.getOrNull() ?: return false
        val marker = runCatching { Json.parseToJsonElement(text) as? JsonObject }.getOrNull() ?: return false
        return marker["schema"]?.toString() == PROVENANCE_SCHEMA.toString()
    }

    companion object {
        const val PROVENANCE_SCHEMA = 1

        /** Not `.gz`: the packager would inflate and rename it. */
        const val HISTORY_PREFIX = "players-historical-"

        /** The career rollup first, then each season from the earliest up. */
        val bundledSeasons: List<Int> =
            listOf(StatScoutSeason.ALL_TIME) + (StatScoutSeason.EARLIEST..StatScoutSeason.BUNDLED_NEWEST).toList()

        /** Streams a JSON array of players without building the whole tree in memory. */
        @OptIn(ExperimentalSerializationApi::class)
        fun readPlayers(stream: InputStream): List<Player> =
            Json.decodeToSequence(stream, JsonElement.serializer(), DecodeSequenceMode.ARRAY_WRAPPED)
                .mapNotNull { element -> (element as? JsonObject)?.let { runCatching { Player.fromJson(it) }.getOrNull() } }
                .toList()
    }
}

fun Player.toJson(): JsonObject = buildJsonObject {
    put("id", playerId)
    put("name", name)
    put("team", team)
    put("position", position)
    put("handedness", handedness)
    put("updated_at", updatedAt.toString())
    season?.let { put("season", it) }
    put("season_type", seasonPhase.raw)
    playerType?.let { put("player_type", it) }
    source?.let { put("source", it) }
    putJsonArray("metrics") { metrics.forEach { add(it.toJson()) } }
    standardStats?.let { stats ->
        putJsonArray("standard_stats") {
            stats.forEach { s -> addJsonObject { put("id", s.id); put("label", s.label); put("value", s.value) } }
        }
    }
    putJsonArray("games") {
        games.forEach { g ->
            addJsonObject {
                put("id", g.id); put("date", g.date.toString()); put("opponent", g.opponent); put("summary", g.summary)
                put("percentile_delta", g.percentileDelta); put("key_metric", g.keyMetric)
            }
        }
    }
}

private fun Metric.toJson(): JsonObject = buildJsonObject {
    put("id", id)
    put("label", label)
    put("value", value)
    put("percentile", percentile)
    put("category", category.raw)
    qualified?.let { put("qualified", it) }
    rankable?.let { put("rankable", it) }
}

object PlayerSnapshotValidator {
    /** 2002-03 and 2003-04 were played by 29 teams; the Bobcats joined in 2004-05. */
    private const val MINIMUM_HISTORICAL_TEAM_COUNT = 29
    private val REQUIRED_TYPES = setOf("g", "f", "c")
    private val REQUIRED_METRICS = setOf("Pts/100", "AST%", "REB%")

    /** Every season the bundle promises, each with a full league and all three position cohorts. */
    fun isCompleteHistorical(players: List<Player>, through: Int = StatScoutSeason.BUNDLED_NEWEST): Boolean {
        val expected = (StatScoutSeason.EARLIEST..through).toSet()
        val grouped = players.filter { it.season in expected && it.seasonPhase == SeasonPhase.REGULAR }.groupBy { it.season!! }
        if (grouped.keys != expected) return false
        return grouped.values.all { seasonPlayers ->
            val teams = seasonPlayers.map { normalizedTeamAbbreviation(it.team) }.toSet()
            val types = seasonPlayers.mapNotNull { it.playerType?.lowercase() }.toSet()
            teams.size >= MINIMUM_HISTORICAL_TEAM_COUNT && types.containsAll(REQUIRED_TYPES) && seasonPlayers.all { it.metrics.isNotEmpty() }
        }
    }

    /**
     * A usable live-season snapshot. `season` is the one expected; null means the
     * newest regular season present, which is how a saved snapshot is judged.
     * Two teams and twenty players is a real opening night; the publisher checks
     * coverage before promotion.
     */
    fun isCompleteCurrent(players: List<Player>, season: Int? = null): Boolean {
        val regular = players.filter { it.seasonPhase == SeasonPhase.REGULAR }
        val target = season ?: regular.mapNotNull { it.season }.maxOrNull() ?: return false
        val current = regular.filter { it.season == target }
        val teams = current.map { normalizedTeamAbbreviation(it.team) }.toSet()
        val types = current.mapNotNull { it.playerType?.lowercase() }.toSet()
        val labels = current.flatMap { it.metrics }.map { it.label }.toSet()
        return teams.size >= 2 && current.size >= 20 && types.containsAll(REQUIRED_TYPES) && labels.containsAll(REQUIRED_METRICS)
    }
}
